CREATE TABLE IF NOT EXISTS network_sites (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS app_users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE,
    role text NOT NULL CHECK (role IN ('Dispatcher', 'Electrician'))
);

CREATE TABLE IF NOT EXISTS cable_tickets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL UNIQUE,
    title varchar(80) NOT NULL CHECK (char_length(title) BETWEEN 5 AND 80),
    description varchar(500) NOT NULL CHECK (char_length(description) BETWEEN 10 AND 500),
    status text NOT NULL CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    site_id integer NOT NULL REFERENCES network_sites(id),
    created_by_user_id integer NOT NULL REFERENCES app_users(id),
    assignee_user_id integer NULL REFERENCES app_users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Ускоряет список заявок, сгруппированный по статусу.
CREATE INDEX IF NOT EXISTS cable_tickets_status_idx ON cable_tickets (status);
-- Ускоряет фильтр заявок по участку сети.
CREATE INDEX IF NOT EXISTS cable_tickets_site_id_idx ON cable_tickets (site_id);
CREATE INDEX IF NOT EXISTS cable_tickets_assignee_idx ON cable_tickets (assignee_user_id);
